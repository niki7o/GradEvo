from __future__ import annotations
import json
import sys
from pathlib import Path
REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT / 'src'))
import pandas as pd
from gradevo import config
from gradevo.metrics import bootstrap as bs
from gradevo.metrics import flops as flops_mod
from gradevo.metrics import hypothesis_tests as ht
OUT = REPO_ROOT / 'paper' / 'results.typ'

def _escape(text: object) -> str:
    s = str(text)
    for ch in ('_', '#', '*', '$', '@'):
        s = s.replace(ch, '\\' + ch)
    return s

def _row_cells(cells: list) -> str:
    return ', '.join((f'[{_escape(c)}]' for c in cells))

def _typst_table(columns: list[str], headers: list[str], rows: list[list]) -> str:
    n = len(headers)
    col_spec = ', '.join(columns)
    header_row = '  table.header(' + _row_cells(headers) + '),\n'
    body = ''
    for row in rows:
        body += '  ' + _row_cells(row) + ',\n'
    return f'#table(\n  columns: ({col_spec}),\n  align: left,\n  stroke: 0.3pt + gray,\n{header_row}{body})\n'

def _load_env(env_id: str):
    slug = env_id.replace('-', '_')

    def _load(name):
        return pd.read_csv(config.DATA_DIR / f'{name}_{slug}.csv')
    fitness_df = _load('fitness')
    curves_df = _load('curves')
    budget_df = _load('budget')
    meta = json.loads((config.DATA_DIR / f'metadata_{slug}.json').read_text())
    return (fitness_df, curves_df, budget_df, meta)

def _summary_block(meta: dict, fitness_df: pd.DataFrame) -> str:
    n = fitness_df.query("method == 'ppo' and condition == 'clean'")['seed'].nunique()
    kind = 'quick verification run' if meta['quick'] else 'full pre-registered run'
    return f"_Environment: `{meta['env_id']}`. Run kind: {kind}. N seeds per method per condition: {n}. Step budget per training run: {meta['step_budget']:,}._\n"

def _fitness_ci_table(fitness_df: pd.DataFrame) -> str:
    methods_present = [m for m in config.METHODS if m in set(fitness_df['method'].unique())]
    rows: list[list] = []
    for method in methods_present:
        for cond in config.CONDITIONS:
            vals = fitness_df[(fitness_df['method'] == method) & (fitness_df['condition'] == cond)]['fitness'].to_numpy()
            if vals.size == 0:
                continue
            ci = bs.bootstrap_mean_ci(vals)
            rows.append([method.upper() if method != 'cmaes' else 'CMA-ES', cond, int(vals.size), f'{ci.point:.1f}', f'[{ci.low:.1f}, {ci.high:.1f}]'])
    return _typst_table(['1.6cm', '1.6cm', '1cm', '1.6cm', '1fr'], ['Method', 'Condition', 'N', 'Mean', '95% BCa CI'], rows)

def _hypothesis_table(fitness_df: pd.DataFrame, curves_df: pd.DataFrame, step_budget: int) -> str:
    results = ht.run_pre_registered_suite(fitness_df, curves_df, step_budget)
    table = ht.results_to_dataframe(results)
    rows: list[list] = []
    for (_, r) in table.iterrows():
        rows.append([r['id'], r['test'], f"{float(r['p_value']):.4f}", f"{float(r['alpha']):.4f}", 'yes' if bool(r['reject_null']) else 'no', f"{float(r['effect_size']):.2f}"])
    return _typst_table(['1.4cm', '1fr', '1.4cm', '1.4cm', '1cm', '1.2cm'], ['ID', 'Test', 'p', 'alpha', 'reject?', 'effect'], rows)

def _flops_table(fitness_df: pd.DataFrame, budget_df: pd.DataFrame, env_id: str) -> str:
    (obs_dim, action_dim) = (8, 2) if 'LunarLander' in env_id else (4, 2)
    steps_by_method = budget_df.set_index('method')['realized_steps_mean'].to_dict()
    seeds = fitness_df.query("condition == 'clean'").drop_duplicates(subset=['method', 'seed'])
    records: list[flops_mod.MethodFlops] = []
    for (_, row) in seeds.iterrows():
        method = row['method']
        if method not in {'ppo', 'es', 'cmaes', 'neat'}:
            continue
        steps = int(steps_by_method.get(method, 0))
        if steps == 0:
            continue
        if method == 'neat':
            rec = flops_mod.estimate_run_flops(method, steps, obs_dim, action_dim, seed=int(row['seed']), neat_nodes=25, neat_connections=60)
        else:
            rec = flops_mod.estimate_run_flops(method, steps, obs_dim, action_dim, seed=int(row['seed']))
        records.append(rec)
    table = flops_mod.flops_table(records)
    rows: list[list] = []
    for (_, r) in table.iterrows():
        rows.append([r['method'].upper() if r['method'] != 'cmaes' else 'CMA-ES', int(r['n_seeds']), f"{r['per_step_forward_flops']:.2e}", f"{r['inference_flops_mean']:.2e}", f"{r['update_flops_mean']:.2e}", f"{r['total_flops_mean']:.2e}"])
    return _typst_table(['1.6cm', '0.8cm', '1.8cm', '1.8cm', '1.8cm', '1.8cm'], ['Method', 'N', 'Forward FLOPs/step', 'Inference FLOPs', 'Update FLOPs', 'Total FLOPs'], rows)

def main() -> None:
    env_id = config.PRIMARY_ENV_ID
    (fitness_df, curves_df, budget_df, meta) = _load_env(env_id)
    parts: list[str] = ['// Auto-generated by scripts/build_results_snapshot.py. Do not edit by hand.\n\n', _summary_block(meta, fitness_df), '\n== 5.1 Per-method final fitness with BCa 95% CIs\n\n', _fitness_ci_table(fitness_df), '\n== 5.2 Pre-registered hypothesis tests (H0-H4)\n\n', _hypothesis_table(fitness_df, curves_df, meta['step_budget']), '\n== 5.3 Compute-fairness sensitivity: FLOPs at matched env-steps\n\n', _flops_table(fitness_df, budget_df, env_id)]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(''.join(parts))
    print(f'Wrote {OUT} ({OUT.stat().st_size} bytes)')
if __name__ == '__main__':
    main()
